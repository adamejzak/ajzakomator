/**
 * The /bin/sh script that swaps the app bundle after the running app has exited. It is generated here (and tested as text
 * and by running it) because nothing can be shown or fixed once the app is gone: every failure path restores the old app.
 * Free of Electron imports.
 *
 * Portability: the script calls every tool (mv, rm, sleep, date, open, xattr, kill, printf) by its bare name and relies on the
 * PATH of its caller (production: /usr/bin:/bin:/usr/sbin:/sbin). Absolute locations differ between macOS (mv and rm live in
 * /bin), Linux and Git for Windows (/usr/bin), so none is hard-coded here or in the tests. It uses only POSIX options
 * (no GNU-only `mv -T`, no `date -d`, no `stat`).
 */

export interface InstallScriptOptions {
  /** Process to wait for (the running app). */
  pid: number;
  /** Absolute path of the installed `.app`. */
  bundle: string;
  /** Absolute path of the verified new `.app`, staged next to `bundle` (same directory, so the swap is two renames). */
  newBundle: string;
  /** Where the old bundle is parked during the swap. */
  backup: string;
  /** Name of the executable inside `Contents/MacOS` of the new bundle. */
  executable: string;
  log: string;
  /** The new app creates this file once its window is up. */
  readyFlag: string;
  /** Written (with the target version) when the update failed and the old app was left or put back in place. */
  failedFlag: string;
  /** Path of this script, removed at the end. */
  selfPath: string;
  /** Extra files or directories removed after a confirmed start (downloaded archive, extraction directory). */
  cleanup: string[];
  fromVersion: string;
  toVersion: string;
  waitSeconds?: number;
  readySeconds?: number;
}

/** The app winds down within 20 s (the shutdown hard limit); the script gives it twice that. */
export const SCRIPT_WAIT_SECONDS = 40;
export const SCRIPT_READY_SECONDS = 30;

/** Single-quotes `value` for /bin/sh; every character is literal inside, including newlines, `$`, backticks and `"`. */
export function shellQuote(value: string): string {
  if (value.includes('\0')) throw new Error('A NUL character cannot be passed to a shell script.');
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

function absolute(name: string, value: string): string {
  if (!value.startsWith('/')) throw new Error(`${name} must be an absolute path.`);
  return shellQuote(value);
}

export function buildInstallScript(o: InstallScriptOptions): string {
  if (!Number.isInteger(o.pid) || o.pid <= 0) throw new Error('pid must be a positive integer.');
  const wait = o.waitSeconds ?? SCRIPT_WAIT_SECONDS;
  const ready = o.readySeconds ?? SCRIPT_READY_SECONDS;
  if (!Number.isInteger(wait) || wait < 0 || !Number.isInteger(ready) || ready < 0) throw new Error('timeouts must be non-negative integers.');
  const cleanup = o.cleanup.map((path) => `rm -rf ${absolute('cleanup', path)}`).join('\n');
  return `#!/bin/sh
# Generated by ajzakomator. Replaces the app after the running instance has quit; restores the old app on any failure.
# Tools are called by bare name; the caller sets PATH.
BUNDLE=${absolute('bundle', o.bundle)}
NEW=${absolute('newBundle', o.newBundle)}
BACKUP=${absolute('backup', o.backup)}
EXE=${shellQuote(o.executable)}
LOG=${absolute('log', o.log)}
READY=${absolute('readyFlag', o.readyFlag)}
FAILED=${absolute('failedFlag', o.failedFlag)}
SELF=${absolute('selfPath', o.selfPath)}
FROM=${shellQuote(o.fromVersion)}
TO=${shellQuote(o.toVersion)}
PID=${o.pid}

log() { printf '%s %s\\n' "$(date '+%Y-%m-%dT%H:%M:%S%z')" "$1" >> "$LOG" 2>/dev/null; }
exists() { [ -e "$1" ] || [ -L "$1" ]; }
launch_old() { open "$BUNDLE" >/dev/null 2>&1 || log "could not start $BUNDLE"; }
finish() { rm -f "$SELF"; exit "$1"; }
mark_failed() { printf '%s\\n' "$TO" > "$FAILED" 2>/dev/null; }
# A removal that stopped halfway leaves the directory behind, and a later mv would then move the source INSIDE it
# (and still exit 0), so every removal is checked.
remove_path() { rm -rf "$1"; if exists "$1"; then return 1; fi; return 0; }
restore_old() {
  if ! remove_path "$BUNDLE"; then log "ROLLBACK FAILED: $BUNDLE could not be removed, the previous version is at $BACKUP"; return 1; fi
  if ! mv "$BACKUP" "$BUNDLE" || exists "$BACKUP" || [ ! -d "$BUNDLE" ]; then log "ROLLBACK FAILED: the previous version is at $BACKUP"; return 1; fi
  log "the previous version was restored"
  return 0
}
# After the old app was moved aside: say why, put it back, start it, remember the failure.
fail_and_restore() {
  log "$1"
  if restore_old; then launch_old; fi
  mark_failed
  finish 1
}
# Before anything was changed: the old app is still in place.
fail_unchanged() {
  log "$1, nothing was changed"
  launch_old
  mark_failed
  finish 1
}

log "update $FROM -> $TO: waiting for process $PID to exit"
waited=0
while kill -0 "$PID" 2>/dev/null; do
  if [ "$waited" -ge ${wait} ]; then
    log "the app is still running after ${wait} seconds, the update is abandoned"
    finish 1
  fi
  sleep 1
  waited=$((waited + 1))
done

if [ ! -f "$NEW/Contents/MacOS/$EXE" ]; then fail_unchanged "the staged app is missing"; fi
if ! remove_path "$BACKUP"; then fail_unchanged "an earlier backup could not be removed"; fi
if ! mv "$BUNDLE" "$BACKUP"; then fail_unchanged "the old app could not be moved aside"; fi
if exists "$BUNDLE"; then fail_and_restore "the old app is still in place after moving it aside"; fi
if ! mv "$NEW" "$BUNDLE"; then fail_and_restore "the new app could not be moved into place, restoring the previous version"; fi
if [ ! -f "$BUNDLE/Contents/MacOS/$EXE" ] || exists "$NEW"; then fail_and_restore "the new app is not in place, restoring the previous version"; fi
xattr -cr "$BUNDLE" >/dev/null 2>&1
rm -f "$READY"
if ! open "$BUNDLE" >/dev/null 2>&1; then fail_and_restore "the new app could not be opened, restoring the previous version"; fi

waited=0
while [ ! -e "$READY" ]; do
  if [ "$waited" -ge ${ready} ]; then
    log "the new app did not report ready within ${ready} seconds; the previous version stays at $BACKUP"
    finish 0
  fi
  sleep 1
  waited=$((waited + 1))
done
log "the new app is running, update $FROM -> $TO complete"
rm -rf "$BACKUP"
${cleanup}
finish 0
`;
}
